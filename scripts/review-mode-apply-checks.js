(async () => {
  const failures = [];
  let assertions = 0;
  const check = (condition, message) => { assertions++; if (!condition) failures.push(message); };
  const api = JquanUIComponents.reviewModeApi;
  const copy = value => JSON.parse(JSON.stringify(value));
  api.configure({ enabled: true, root: '#review-root', allowURL: false });
  api.open();
  api.select('#title');
  api.setText('计划标题');
  api.setUtility('font-size', 'text-lg');
  const plan = JSON.parse(api.exportPlan('json'));
  check(plan.schemaVersion === 1 && plan.changes.length === 2, 'exported plan has two final changes');
  check(api.reset(), 'reset exported preview');
  const dry = api.applyPlan(plan);
  check(dry.ok && dry.dryRun && dry.applied === 0 && dry.issues.length === 0, 'default dry-run preflights');
  check(document.getElementById('title').textContent === '审查标题' && !document.getElementById('title').classList.contains('text-lg'), 'dry-run leaves DOM unchanged');
  const applied = api.applyPlan(plan, { dryRun: false });
  check(applied.ok && !applied.dryRun && applied.applied === 2, 'explicit apply writes both fields');
  check(document.getElementById('title').textContent === '计划标题' && document.getElementById('title').classList.contains('text-lg'), 'explicit apply updates preview');
  check(api.changes().length === 2 && api.state().canUndo, 'applied plan tracked');
  check(api.undo() && api.redo(), 'plan undo redo');
  check(api.reset(), 'restore applied plan');
  const conflictPlan = JSON.parse(JSON.stringify(plan));
  document.getElementById('title').textContent = '外部更新';
  const conflict = api.applyPlan(conflictPlan, { dryRun: false });
  check(!conflict.ok && conflict.applied === 0 && conflict.issues.some(issue => issue.code === 'before-mismatch'), 'before mismatch blocks the whole batch');
  check(!document.getElementById('title').classList.contains('text-lg'), 'blocked batch does not partially write');
  const unstable = JSON.parse(JSON.stringify(plan));
  unstable.changes[0].target.stable = false;
  const rejected = api.applyPlan(unstable);
  check(!rejected.ok && rejected.issues.some(issue => issue.code === 'unstable-target'), 'unstable locator is rejected');
  document.getElementById('title').firstChild.data = '审查标题';
  const has = (p, code) => { const r = api.applyPlan(p, { dryRun: false }); return !r.ok && r.applied === 0 && r.issues.some(issue => issue.code === code); };
  const mutated = (fn, code) => { const p = copy(plan); fn(p); check(has(p, code), code); };
  mutated(p => p.page += '-different', 'page-mismatch');
  mutated(p => p.schemaVersion = 99, 'invalid-plan');
  mutated(p => p.changes[0].status = 'conflict', 'non-ready-status');
  mutated(p => p.changes[0].status = 'detached', 'non-ready-status');
  mutated(p => p.changes[0].target.selector = '#missing-review-target', 'target-not-found');
  mutated(p => p.changes[0].target.selector = '[', 'invalid-selector');
  mutated(p => p.changes[0].target.selector = 'h1', 'unstable-target');
  mutated(p => p.changes[0].tag = 'button', 'unstable-target');
  mutated(p => p.changes.push(copy(p.changes[0])), 'duplicate-field');
  mutated(p => p.changes[1].after = ['text-[999px]'], 'invalid-value');
  mutated(p => p.changes[1].after = ['hover:text-lg'], 'invalid-value');
  mutated(p => p.changes[1].after = ['text-sm', 'text-lg'], 'invalid-value');
  mutated(p => p.changes[0].field = 'text:99999', 'invalid-value');
  mutated(p => p.changes[0].after = null, 'invalid-value');
  check(has('{', 'invalid-plan') && has(null, 'invalid-plan'), 'malformed input');
  const cycle = {}; cycle.self = cycle;
  check(has(cycle, 'invalid-plan') && has(' '.repeat(1048577), 'invalid-plan'), 'cycle size bound');
  const root = document.getElementById('review-root'), title = document.getElementById('title');
  const duplicate = title.cloneNode(true); root.append(duplicate);
  check(has(plan, 'target-ambiguous'), 'duplicate stable key'); duplicate.remove();
  const link = document.createElement('a'); link.id = 'review-apply-link'; link.href = '/before'; root.append(link);
  api.select(link); api.setAttribute('href', '/after'); const linkPlan = JSON.parse(api.exportPlan('json')); api.reset();
  linkPlan.changes[0].after = 'javascript:window.badApply=true';
  check(has(linkPlan, 'invalid-value') && link.getAttribute('href') === '/before', 'href protocol rules'); link.remove();
  const empty = document.createElement('div'); empty.id = 'review-apply-empty'; root.append(empty);
  api.select(empty); api.setText('new direct text'); const emptyPlan = JSON.parse(api.exportPlan('json')); api.reset();
  check(api.applyPlan(emptyPlan, { dryRun: false }).ok && empty.textContent === 'new direct text', 'empty direct text insertion');
  check(api.reset() && !empty.childNodes.length, 'empty text restore'); empty.remove();
  api.close(); check(api.applyPlan(plan).ok && has(plan, 'not-active'), 'closed dry-run only'); api.open();
  check(api.applyPlan(JSON.stringify(plan), { dryRun: false }).ok, 'apply JSON before destroy'); api.destroy();
  check(title.textContent === '审查标题', 'destroy restores plan');
  check(has(plan, 'not-configured'), 'disabled rejects plan');
  const selectApi = await JquanUI.import('select', { install: false });
  const source = document.createElement('select'); source.id = 'review-apply-select'; source.innerHTML = '<option value="a">A</option><option value="b" selected>B</option>'; root.append(source);
  const handle = selectApi.mount(source, { searchable: true, clearable: true });
  api.configure({ enabled: true, root, allowURL: false }); api.open(); api.select(title); api.setText('component batch'); api.select(source); api.setComponentOption('select', 'clearable', false);
  const componentPlan = JSON.parse(api.exportPlan('json')); api.reset();
  check(componentPlan.schemaVersion === 2 && api.applyPlan(componentPlan).ok, 'component schema preflight');
  check(api.applyPlan(componentPlan, { dryRun: false }).ok && !handle.state().clearable && source.value === 'b', 'component setter preserves value');
  check(api.reset() && handle.state().clearable, 'component reset');
  source.addEventListener('jquan:select:update', () => { title.firstChild.data = 'external during setter'; }, { once: true });
  const interrupted = api.applyPlan(componentPlan, { dryRun: false });
  check(!interrupted.ok && interrupted.issues.some(issue => issue.code === 'rollback-conflict') && title.textContent === 'external during setter' && handle.state().clearable, 'rollback preserves external update');
  api.destroy(); title.firstChild.data = '审查标题';
  api.configure({ enabled: true, root, allowURL: false }); api.open();
  source.addEventListener('jquan:select:update', () => api.configure({ enabled: true, root, allowURL: false }), { once: true });
  check(!api.applyPlan(componentPlan, { dryRun: false }).ok && !api.state().canUndo && !api.changes().length && title.textContent === '审查标题', 'reconfigure retires plan');
  handle.destroy(); source.remove();
  api.destroy();
  return { assertions, failures };
})()
